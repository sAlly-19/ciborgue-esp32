"""Generate ESP32 face assets from the Qt bench renderer (requires PySide6)."""
import ast
import math
from pathlib import Path
from types import SimpleNamespace

from PySide6.QtCore import QPointF, QRectF, Qt
from PySide6.QtGui import QColor, QBrush, QImage, QPainter, QPainterPath, QPen

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "app" / "face_canvas.py"
MOUTHS = (
    "NEUTRAL", "SPEAK", "LISTEN", "THINK", "HAPPY_OPEN", "SURPRISED",
    "SAD", "ANGRY", "WINK", "SLEEPY", "FEAR", "DISGUST", "CONTEMPT",
    "SHAME", "DESPAIR", "MALICE",
    "CURIOUS", "BORED", "SILENT", "ANGEL", "COOL", "CRAZY", "LIAR",
)
EMOTIONS = (
    "NEUTRAL", "HAPPY", "SAD", "ANGRY", "SURPRISED", "WINK", "LOVE",
    "SLEEPY", "FEAR", "DISGUST", "CONTEMPT", "SHAME", "DESPAIR", "MALICE",
    "CURIOUS", "BORED", "SILENT", "ANGEL", "COOL", "CRAZY", "LIAR",
)
POSE_FIELDS = (
    "w_scale", "lh_scale", "rh_scale", "gaze_x", "gaze_y", "tilt", "shake_amp",
    "l_top_l", "l_top_r", "r_top_l", "r_top_r", "l_bot_l", "l_bot_r",
    "r_bot_l", "r_bot_r", "bot_arc", "fear_corner", "blush_alpha",
    "blush_intensity", "blush_y_off", "sweat_alpha", "sweat_scale", "allow_idle_gaze",
)
SIZE = 88
CENTER = SIZE // 2


def load_reference():
    tree = ast.parse(SOURCE.read_text(encoding="utf-8"))
    canvas = next(node for node in tree.body if isinstance(node, ast.ClassDef)
                  and node.name == "FaceCanvas296x240")
    draw_mouth = next(node for node in canvas.body if isinstance(node, ast.FunctionDef)
                      and node.name == "_draw_mouth_shape")
    pose_nodes = [
        node for node in tree.body if
        (isinstance(node, ast.Assign)
         and any(isinstance(target, ast.Name) and target.id in ("_BASE_POSE", "EMOTION_POSES")
                 for target in node.targets))
        or (isinstance(node, ast.FunctionDef) and node.name == "_pose")
    ]
    scope = dict(globals())
    exec(compile(ast.Module(body=[*pose_nodes, draw_mouth], type_ignores=[]),
                 str(SOURCE), "exec"), scope)
    return scope["EMOTION_POSES"], scope["_draw_mouth_shape"]


def rasterize(draw, key, color):
    image = QImage(SIZE, SIZE, QImage.Format.Format_RGB32)
    image.fill(Qt.GlobalColor.black)
    painter = QPainter(image)
    try:
        painter.setRenderHint(QPainter.RenderHint.Antialiasing)
        painter.translate(CENTER, CENTER)
        painter.scale(1.16, 1.16)
        draw(SimpleNamespace(anim_tick=0.0), painter, key, 0.0, 0.0, color)
    finally:
        painter.end()
    return image


def mouth_asset(draw, key):
    base = rasterize(draw, key, QColor(0, 0, 0))
    white = rasterize(draw, key, QColor(255, 255, 255))
    colored = [(x, y) for y in range(SIZE) for x in range(SIZE)
               if white.pixel(x, y) & 0xFFFFFF or base.pixel(x, y) & 0xFFFFFF]
    left, right = min(x for x, _ in colored), max(x for x, _ in colored)
    top, bottom = min(y for _, y in colored), max(y for _, y in colored)
    assert 0 < left <= right < SIZE - 1 and 0 < top <= bottom < SIZE - 1, key
    pixels = []
    for y in range(top, bottom + 1):
        for x in range(left, right + 1):
            dark = base.pixel(x, y)
            tint = max(0, (white.pixel(x, y) & 255) - (dark & 255))
            pixels.append((tint << 24) | (dark & 0xFFFFFF))
    return left - CENTER, top - CENTER, right - left + 1, bottom - top + 1, pixels


def cpp_float(value):
    return f"{float(value):.6f}".rstrip("0").rstrip(".") + ("f" if float(value) % 1 else ".0f")


def main():
    poses, draw = load_reference()
    lines = ["// Generated by tools/generate_bench_faces.py from app/face_canvas.py.",
             "#pragma once", "#include <stdint.h>", "", "namespace bench_face {",
             "struct Pose {", *[f"    float {field};" for field in POSE_FIELDS], "};",
             "constexpr Pose poses[] = {"]
    lines.extend("    {" + ", ".join(cpp_float(poses[key][field]) for field in POSE_FIELDS)
                 + f"}}, // {key}" for key in EMOTIONS)
    lines.extend(["};", "", "struct Mouth {",
                  "    int8_t x, y;", "    uint8_t width, height;",
                  "    const uint32_t* pixels;", "};"])
    descriptors = []
    for key in MOUTHS:
        if key in ("SPEAK", "SILENT"):
            descriptors.append("    {0, 0, 0, 0, nullptr},")
            continue
        x, y, w, h, pixels = mouth_asset(draw, key)
        name = key.lower()
        lines.append(f"constexpr uint32_t {name}[] = {{")
        for i in range(0, len(pixels), 10):
            lines.append("    " + ", ".join(f"0x{pixel:08x}" for pixel in pixels[i:i + 10]) + ",")
        lines.append("};")
        descriptors.append(f"    {{{x}, {y}, {w}, {h}, {name}}},")
    lines.extend(["", "constexpr Mouth mouths[] = {", *descriptors, "};", "} // namespace bench_face"])
    (ROOT / "include" / "bench_face_assets.h").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
